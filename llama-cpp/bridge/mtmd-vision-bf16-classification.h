inline int32_t lcb_mtmd_classify_metadata(int32_t has_vision, const char * common, const char * vision) {
    if (has_vision == 0)
        return MTMD_VISION_BF16_CANDIDATE_NOT_APPLICABLE;
    if (has_vision != 1)
        return MTMD_VISION_BF16_CANDIDATE_UNKNOWN;
    const char * name = common && common[0] ? common : vision;
    if (!name || !name[0])
        return MTMD_VISION_BF16_CANDIDATE_UNKNOWN;
    size_t length = 0;
    while (length < 128 && name[length])
        ++length;
    if (length == 128)
        return MTMD_VISION_BF16_CANDIDATE_UNKNOWN;
    auto type = clip_projector_type_from_string(name);
    // Same vision alias normalization as the pinned load_hparams. Source hash
    // and all-name tests guard this small private-interface dependency.
    if (type == PROJECTOR_TYPE_QWEN25O)
        type = PROJECTOR_TYPE_QWEN25VL;
    return lcb_mtmd_review_projector(type);
}
